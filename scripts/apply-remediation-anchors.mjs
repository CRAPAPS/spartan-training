/**
 * apply-remediation-anchors.mjs
 *
 * Turns the reviewed anchor decisions into the UPDATE block inside
 * supabase/migrations/028_corrective_action.sql, between the ANCHORS markers.
 *
 * Sources, in precedence order:
 *   1. docs/superpowers/specs/2026-09-09-anchor-answers.txt        (reviewed, wins)
 *   2. docs/superpowers/specs/2026-09-08-remediation-anchors.json  (HIGH only)
 *
 * Merge and SQL generation live in scripts/lib/anchors.mjs so they can be unit
 * tested — see src/__tests__/anchors.test.ts.
 *
 * SAFETY: every anchor is re-verified against the live schema before anything is
 * written — the slide must exist, be in the SAME TRACK, and be in a module at or
 * before the question's module in sequence_order. A wrong anchor sends a learner to
 * unrelated material while the platform records that they reviewed the source, so
 * this refuses to write rather than emitting a bad UPDATE.
 *
 * Re-runnable: replaces whatever currently sits between the markers.
 * Does NOT write to the database.
 *
 * Usage:
 *   node scripts/apply-remediation-anchors.mjs
 *   node scripts/apply-remediation-anchors.mjs --dry-run
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createClient } from '@supabase/supabase-js';
import { parseAnswers, mergeAnchors, toSqlLines } from './lib/anchors.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function loadEnv() {
  const raw = readFileSync(resolve(ROOT, '.env.local'), 'utf8');
  for (const line of raw.split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    if (!process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
loadEnv();

const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false } },
);

const DRY = process.argv.includes('--dry-run');

const ANSWERS = resolve(ROOT, 'docs/superpowers/specs/2026-09-09-anchor-answers.txt');
const PROPOSALS = resolve(ROOT, 'docs/superpowers/specs/2026-09-08-remediation-anchors.json');
const MIGRATION = resolve(ROOT, 'supabase/migrations/028_corrective_action.sql');

const BEGIN = '-- >>> ANCHORS BEGIN';
const END = '-- >>> ANCHORS END';

const moduleOfSlide = (slideId) => slideId.replace(/-s\d+$/, '');

async function main() {
  const answers = parseAnswers(readFileSync(ANSWERS, 'utf8'));
  const proposals = JSON.parse(readFileSync(PROPOSALS, 'utf8'));
  const anchors = mergeAnchors(proposals, answers);

  // ── Re-verify against the live schema ─────────────────────────────────────
  const { data: questions } = await db
    .from('quiz_questions')
    .select('id, module_id, is_critical')
    .eq('is_critical', true);
  const qBy = new Map((questions ?? []).map((q) => [q.id, q]));

  const { data: mods } = await db.from('mjm_modules').select('id, track, sequence_order');
  const modBy = new Map((mods ?? []).map((m) => [m.id, m]));

  const { data: lessons } = await db.from('module_lessons').select('module_id, slides');
  const slideIds = new Set();
  for (const l of lessons ?? []) {
    (Array.isArray(l.slides) ? l.slides : []).forEach((s, i) => {
      slideIds.add(s.slideId ?? `${l.module_id}-s${String(i).padStart(2, '0')}`);
    });
  }

  const errors = [];
  for (const [questionId, slideId] of anchors) {
    const q = qBy.get(questionId);
    if (!q) { errors.push(`${questionId}: not a critical question (or does not exist)`); continue; }
    if (!slideId) continue; // NONE — ships unanchored, by design

    if (!slideIds.has(slideId)) { errors.push(`${questionId} -> ${slideId}: no such slide`); continue; }

    const sm = modBy.get(moduleOfSlide(slideId));
    const qm = modBy.get(q.module_id);
    if (!sm || !qm) { errors.push(`${questionId} -> ${slideId}: module lookup failed`); continue; }
    if (sm.track !== qm.track) {
      errors.push(`${questionId} -> ${slideId}: wrong track (${sm.track} vs ${qm.track})`);
    } else if (sm.sequence_order > qm.sequence_order) {
      errors.push(`${questionId} -> ${slideId}: forward reference — ${sm.id} is position ${sm.sequence_order}, after ${qm.id} at ${qm.sequence_order}`);
    }
  }

  if (errors.length) {
    console.error(`\nREFUSING TO WRITE — ${errors.length} invalid anchor(s):`);
    for (const e of errors) console.error(`  ${e}`);
    console.error('');
    process.exit(1);
  }

  // ── Emit ──────────────────────────────────────────────────────────────────
  const sql = toSqlLines(anchors);
  const anchored = sql.length;
  const unanchored = [...anchors.values()].filter((v) => !v).length;
  const crossModule = [...anchors].filter(
    ([qid, sid]) => sid && moduleOfSlide(sid) !== qBy.get(qid)?.module_id,
  ).length;

  const block = [
    BEGIN,
    '-- Generated by scripts/apply-remediation-anchors.mjs — do not edit by hand.',
    `-- ${anchored} of ${qBy.size} critical questions anchored; ${unanchored} ship unanchored`,
    `-- and degrade to a module-overview link. ${crossModule} anchors cross modules.`,
    ...sql,
    END,
  ].join('\n');

  const migration = readFileSync(MIGRATION, 'utf8');
  const start = migration.indexOf(BEGIN);
  const stop = migration.indexOf(END);
  if (start === -1 || stop === -1) {
    console.error(`Markers not found in ${MIGRATION}. Expected:\n${BEGIN}\n${END}`);
    process.exit(1);
  }

  console.log(`\nCritical questions: ${qBy.size}`);
  console.log(`Anchored:           ${anchored}   (${crossModule} cross-module)`);
  console.log(`Unanchored (NONE):  ${unanchored}`);
  console.log('All anchors verified: slide exists, same track, not a forward reference.');

  if (DRY) {
    console.log('\n--dry-run: migration not modified.\n');
    return;
  }

  writeFileSync(MIGRATION, migration.slice(0, start) + block + migration.slice(stop + END.length));
  console.log(`\nWritten into ${MIGRATION}\n`);
}

main().catch((e) => { console.error(e); process.exit(1); });
